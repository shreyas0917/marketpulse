"""Generate SLO recording and burn-rate alerting rules (spec section 6).

Writes observability/prometheus/rules/slo-recording.yml and slo-alerts.yml.
The rules are generated so every SLI x window combination follows exactly the
same pattern; regenerate with `make slo-rules` after changing a target.
"""

from __future__ import annotations

from pathlib import Path

RULES = Path(__file__).resolve().parent.parent / "observability" / "prometheus" / "rules"
RUNBOOK_BASE = "https://github.com/shreyas0917/marketpulse/blob/main/docs/runbooks"
WINDOWS = ("5m", "30m", "1h", "6h", "3d")
Q = 'route="/v1/quotes/{symbol}"'

# name -> (title, target, good expr, total expr); "WINDOW" is replaced by each window.
SLIS: dict[str, tuple[str, float, str, str]] = {
    "availability": (
        "Availability",
        0.999,
        "sum(rate(http_requests_total{" + Q + ', status!~"5.."}[WINDOW]))',
        "sum(rate(http_requests_total{" + Q + "}[WINDOW]))",
    ),
    "latency": (
        "Latency",
        0.99,
        "sum(rate(http_request_duration_seconds_bucket{" + Q + ', le="0.25"}[WINDOW]))',
        "sum(rate(http_request_duration_seconds_count{" + Q + "}[WINDOW]))",
    ),
    "freshness": (
        "Freshness",
        0.99,
        'sum(rate(quote_age_seconds_bucket{le="2.0"}[WINDOW]))',
        "sum(rate(quote_age_seconds_count[WINDOW]))",
    ),
    "ingestion_lag": (
        "IngestionLag",
        0.99,
        'sum(rate(ingestion_lag_seconds_bucket{le="1.0"}[WINDOW]))',
        "(\n              sum(rate(ingestion_lag_seconds_count[WINDOW]))\n              +\n"
        '              sum(rate(events_processed_total{result="dead_lettered"}[WINDOW]))\n'
        "            )",
    ),
}

SUMMARIES = {
    "availability": "Quote API is returning too many 5xx responses",
    "latency": "Too many quote requests take longer than 250 ms",
    "freshness": "Too many served quotes are older than 2 s",
    "ingestion_lag": "Too many events take longer than 1 s to ingest",
}

# The SLO window. Its error ratio is weighted by events: sum of good rates / sum of total rates
# over the window (averaging short-window ratios would weight a quiet minute like a busy one).
# Prometheus can only answer for the history it keeps: with shorter retention the "30d" rules
# cover the retention period instead (see docs/slos.md).
SLO_WINDOW = "30d"
LOW_BUDGET = 0.25  # error-budget policy: below 25 % remaining, feature releases freeze

# (alert suffix, long window, short window, burn factor, severity, budget consumed)
BURNS = (
    ("FastBurn", "1h", "5m", 14.4, "page", "2%"),
    ("FastBurn", "6h", "30m", 6, "page", "5%"),
    ("SlowBurn", "3d", "6h", 1, "ticket", "10%"),
)

HEADER = "# Generated by scripts/gen-slo-rules.py - do not edit by hand.\n"


def recording() -> str:
    out = [HEADER, "groups:"]
    for sli, (_, target, good, total) in SLIS.items():
        out.append(f"  - name: slo-{sli.replace('_', '-')}")
        out.append("    rules:")
        for w in WINDOWS:
            out.append(f"      - record: sli:{sli}:error_ratio_rate{w}")
            out.append("        expr: |")
            out.append("          1 - (")
            out.append(f"            {good.replace('WINDOW', w)}")
            out.append("            /")
            out.append(f"            {total.replace('WINDOW', w)}")
            out.append("          )")
            out.append("        labels:")
            out.append(f"          slo: {sli}")
            out.append(f'          slo_target: "{target}"')
        for kind, expr in (("good", good), ("total", total)):
            out.append(f"      - record: sli:{sli}:{kind}_rate5m")
            out.append("        expr: |")
            out.append(f"          {expr.replace('WINDOW', '5m')}")
            out.append("        labels:")
            out.append(f"          slo: {sli}")
            out.append(f'          slo_target: "{target}"')
    for sli, (_, target, _, _) in SLIS.items():
        budget = round(1 - target, 6)
        w = SLO_WINDOW
        out.append(f"  - name: slo-{sli.replace('_', '-')}-{w}")
        out.append("    interval: 5m")
        out.append("    rules:")
        out.append(f"      - record: sli:{sli}:error_ratio_{w}")
        out.append("        expr: |")
        out.append("          1 - (")
        out.append(f"            sum_over_time(sli:{sli}:good_rate5m[{w}])")
        out.append("            /")
        out.append(f"            sum_over_time(sli:{sli}:total_rate5m[{w}])")
        out.append("          )")
        out.append(f"      - record: slo:{sli}:compliance_{w}")
        out.append("        expr: |")
        out.append(f"          1 - sli:{sli}:error_ratio_{w}")
        out.append(f"      - record: slo:{sli}:error_budget_remaining_{w}")
        out.append("        expr: |")
        out.append(f"          1 - (sli:{sli}:error_ratio_{w} / {budget})")
    return "\n".join(out) + "\n"


def alerts() -> str:
    out = [HEADER, "groups:", "  - name: slo-burn-rate", "    rules:"]
    for sli, (title, target, _, _) in SLIS.items():
        budget = round(1 - target, 6)
        runbook = f"{RUNBOOK_BASE}/{sli.replace('_', '-')}-burn.md"
        for suffix, long_w, short_w, factor, severity, consumed in BURNS:
            anchor = "fast-burn" if suffix == "FastBurn" else "slow-burn"
            out += [
                f"      - alert: {title}{suffix}",
                "        expr: |",
                f"          sli:{sli}:error_ratio_rate{long_w} > ({factor} * {budget})",
                "          and",
                f"          sli:{sli}:error_ratio_rate{short_w} > ({factor} * {budget})",
                "        labels:",
                f"          severity: {severity}",
                f"          slo: {sli}",
                f"          window: {long_w}/{short_w}",
                "        annotations:",
                f'          summary: "{SUMMARIES[sli]} ({factor}x burn over {long_w}/{short_w})"',
                f'          description: "At this rate {consumed} of the 30-day {sli} error budget'
                f' is used within {long_w}."',
                f"          runbook_url: {runbook}#{anchor}",
            ]
    out += ["  - name: slo-error-budget", "    rules:"]
    for sli, (title, _, _, _) in SLIS.items():
        w = SLO_WINDOW
        out += [
            f"      - alert: {title}ErrorBudgetLow",
            "        expr: |",
            f"          slo:{sli}:error_budget_remaining_{w} < {LOW_BUDGET}",
            "        for: 15m",
            "        labels:",
            "          severity: ticket",
            f"          slo: {sli}",
            f"          window: {w}",
            "        annotations:",
            f'          summary: "Less than {LOW_BUDGET:.0%} of the {w} {sli} error budget'
            ' is left"',
            '          description: "{{ $value | humanizePercentage }} of the budget remains. '
            'Error-budget policy: freeze feature releases; reliability fixes only."',
            f"          runbook_url: {RUNBOOK_BASE}/error-budget.md#budget-low",
        ]
    return "\n".join(out) + "\n"


def main() -> None:
    (RULES / "slo-recording.yml").write_text(recording(), encoding="utf-8", newline="\n")
    (RULES / "slo-alerts.yml").write_text(alerts(), encoding="utf-8", newline="\n")
    print(f"wrote {RULES / 'slo-recording.yml'} and {RULES / 'slo-alerts.yml'}")


if __name__ == "__main__":
    main()
